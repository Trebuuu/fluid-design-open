/* gen-springs.mjs — write assets/fg3-springs.css from assets/spring.js, and
   the reduced-motion twin (§13b) of assets/fg3-motion.css from its §13.

     node tools/gen-springs.mjs            (writes both)
     node tools/gen-springs.mjs --check    (exit 1 if either on disk is stale)

   WHY GENERATED: a hand-copied linear() is a derived value that drifts from its
   constants; a head-injected <style> loses the cascade on the artifact host. So the numbers are computed by the same spring.js the page
   runs, and pages link the static result.

   THE TWIN: fg3-motion.css §13 is written once, inside
   @media (prefers-reduced-motion: reduce). CSS cannot also apply one rule list
   under a class, so §13b — between the @rm-twin markers — is that list again
   with every selector scoped to :where(html.fd-reduced-motion,
   [data-reduce-preview]) (view-transition pseudo-elements: the html class
   only). :where() adds no specificity, so the twin wins and loses exactly
   where §13 does. Edit §13, re-run this. */
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'assets/spring.js');
const OUT = path.join(ROOT, 'assets/fg3-springs.css');

const sandbox = {}; sandbox.globalThis = sandbox;
vm.runInNewContext(readFileSync(SRC, 'utf8'), sandbox, { filename: SRC });
const S = sandbox.SPRING;

const f = (n, d) => (Math.round(n * 10 ** d) / 10 ** d).toFixed(d);
const rows = S.table();
const head = ['name', 'duration', 'bounce', 'zeta', 'k', 'c', 'mass', 'settle', 'peak'];
const body = rows.map(r => [
  r.name,
  r.mkc ? `${r.ms}ms*` : f(r.duration, 3) + 's',
  r.mkc ? '-' : f(r.bounce, 3),
  f(r.zeta, 3),
  f(r.stiffness, 1),
  f(r.damping, 2),
  String(r.mass),
  r.ms + 'ms',
  r.peak > 1.0005 ? f(r.peak, 4) : '-',
]);
const w = head.map((h, i) => Math.max(h.length, ...body.map(b => b[i].length)));
const line = cells => '   ' + cells.map((c, i) => c.padEnd(w[i])).join('  ');

const css = [];
for (const r of rows) {
  const s = S.Spring(r.name);
  const lin = s.linear();
  if (/NaN|Infinity/.test(lin)) throw new Error(`spring ${r.name} produced ${lin}`);
  css.push(`  --sp-${r.name}: ${lin};`);
  css.push(`  --sp-${r.name}-ms: ${s.ms()}ms;`);
}

const out = `/* ═══════════════════════════════════════════════════════════════════════════
   fg3-springs.css — GENERATED by tools/gen-springs.mjs from assets/spring.js.
   Do not edit by hand; change the constants in spring.js and re-run.

   Every named spring as --sp-<name> (a CSS linear() easing) and
   --sp-<name>-ms (the duration that easing is normalised to). Use them as a
   pair — linear() is normalised to the transition's own duration:
       transition: transform var(--sp-snappy-ms) var(--sp-snappy);

   settle = time after which the spring stays within ±0.2 % of its target.
   peak   = maximum value of the unit step response (overshoot), "-" = none.
   * nav-in / nav-out are the localnav easings spring(m, k, c, v0),
     played over a FIXED 600 / 400 ms; their ζ is the true
     damping ratio, but the solver takes the critical branch for ζ ≥ 1.

${line(head)}
${body.map(line).join('\n')}
   ═══════════════════════════════════════════════════════════════════════════ */
:root{
${css.join('\n')}
}
`;

/* ── the reduced-motion twin ─────────────────────────────────────────────── */
const MOTION_CSS = path.join(ROOT, 'assets/fg3-motion.css');
const RM_SOURCE = '@media (prefers-reduced-motion: reduce){';
const TWIN_BEGIN = '/* @rm-twin:begin */', TWIN_END = '/* @rm-twin:end */';
const SCOPE = ':where(html.fd-reduced-motion,[data-reduce-preview])', SCOPE_DOC = ':where(html.fd-reduced-motion)';

/* index just past the '}' that closes the block opening at css[open] === '{' */
function blockEnd(css, open) {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css.startsWith('/*', i)) { i = css.indexOf('*/', i + 2) + 1; if (i === 0) throw new Error('unclosed comment'); continue; }
    if (css[i] === '"' || css[i] === "'") { i = css.indexOf(css[i], i + 1); if (i < 0) throw new Error('unclosed string'); continue; }
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return i + 1;
  }
  throw new Error('unbalanced braces after ' + css.slice(open - 40, open));
}
/* split a selector list on top-level commas */
function selectors(list) {
  const out = []; let depth = 0, cur = '';
  for (const c of list) {
    if (c === '(' || c === '[') depth++; else if (c === ')' || c === ']') depth--;
    if (c === ',' && !depth) { out.push(cur.trim()); cur = ''; } else cur += c;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}
const scoped = s => s.startsWith('::') ? SCOPE_DOC + s : SCOPE + ' ' + s;
/* the rules of a block body, each selector scoped; @-blocks (starting-style) recurse */
function twin(body, indent) {
  const out = []; let i = 0;
  const noComments = s => s.replace(/\/\*[\s\S]*?\*\//g, '');
  while (i < body.length) {
    if (/\s/.test(body[i])) { i++; continue; }
    if (body.startsWith('/*', i)) { i = body.indexOf('*/', i) + 2; continue; }
    const open = body.indexOf('{', i);
    if (open < 0) { if (noComments(body.slice(i)).trim()) throw new Error('stray text in §13: ' + body.slice(i, i + 60)); break; }
    const prelude = noComments(body.slice(i, open)).trim().replace(/\s+/g, ' '), end = blockEnd(body, open);
    const inner = body.slice(open + 1, end - 1);
    if (prelude.startsWith('@')) out.push(indent + prelude + '{\n' + twin(inner, indent + '  ') + '\n' + indent + '}');
    else out.push(indent + selectors(prelude).map(scoped).join(',\n' + indent) + '{' + noComments(inner).replace(/\s+/g, ' ').replace(/\s*$/, ' ') + '}');
    i = end;
  }
  return out.join('\n');
}
const motionCss = readFileSync(MOTION_CSS, 'utf8');
const src13 = motionCss.indexOf(RM_SOURCE);
if (src13 < 0 || motionCss.indexOf(RM_SOURCE, src13 + 1) >= 0) throw new Error(`fg3-motion.css needs exactly one "${RM_SOURCE}" (§13)`);
const body13 = motionCss.slice(src13 + RM_SOURCE.length, blockEnd(motionCss, src13 + RM_SOURCE.length - 1) - 1);
const tb = motionCss.indexOf(TWIN_BEGIN), te = motionCss.indexOf(TWIN_END);
if (tb < 0 || te < tb) throw new Error(`fg3-motion.css has no ${TWIN_BEGIN} … ${TWIN_END} region for the twin`);
const twinCss = TWIN_BEGIN + '\n' + twin(body13, '') + '\n' + TWIN_END;
const motionOut = motionCss.slice(0, tb) + twinCss + motionCss.slice(te + TWIN_END.length);

if (process.argv.includes('--check')) {
  let cur = '', stale = [];
  try { cur = readFileSync(OUT, 'utf8'); } catch {}
  if (cur !== out) stale.push('fg3-springs.css');
  if (motionOut !== motionCss) stale.push('fg3-motion.css §13b (the reduced-motion twin)');
  if (stale.length) { console.error(stale.join(' and ') + ' stale — run node tools/gen-springs.mjs'); process.exit(1); }
  console.log('fg3-springs.css is current (' + rows.length + ' springs); fg3-motion.css §13b mirrors §13');
} else {
  writeFileSync(OUT, out);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' — ' + rows.length + ' springs, ' + out.length + ' bytes');
  if (motionOut !== motionCss) { writeFileSync(MOTION_CSS, motionOut); console.log('wrote ' + path.relative(ROOT, MOTION_CSS) + ' §13b — the reduced-motion twin'); }
  else console.log(path.relative(ROOT, MOTION_CSS) + ' §13b already mirrors §13');
}
