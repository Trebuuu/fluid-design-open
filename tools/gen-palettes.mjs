/* gen-palettes.mjs — write the static colour stylesheets from assets/palette.js.

     node tools/gen-palettes.mjs            write assets/fg3-color.css, print the report
     node tools/gen-palettes.mjs --check    write nothing; exit 1 if a file on disk is stale

   Pages LINK these files; they never run the engine. A head-injected <style>
   loses the cascade to a body-linked stylesheet on the Artifact host, and a
   generator shipped to every visitor recomputes a constant.

   Exit code 1 if any role misses its target against the hardest ground it can
   land on, or (with --check) if a generated file differs from what is on disk. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(path.join(ROOT, 'assets/palette.js'), 'utf8');
const win = {};
new Function('window', src)(win);
const P = win.PALETTE;

/* file stem → preset. The only palette is the Fluid default (violet). */
export const FILES = { 'fg3-color': 'fluid' };

function header(p, stem) {
  const clean = s => String(s).replace(/\*\//g, '* /');   /* a stray close ends the comment early */
  return `/* ${stem}.css — GENERATED by tools/gen-palettes.mjs from assets/palette.js. Do not edit.
   ${clean(p.label)}
   brand ${p.accent} · read from: ${clean(p.from)}
   Roles: SPEC §2. label-3 is the tertiary label on the cool neutrals (3:1, large text and
   glyphs); use --label-2 for text at 17px and below. --on-art-* assume art under copy
   no lighter than oklch L ${P.ART.dark.L} (dark) / no darker than L ${P.ART.light.L} (light).
   Contrast: ${p.report.filter(r => !r.more).length} checks, ${p.failures.length} below target. */`;
}

const check = process.argv.includes('--check');
let failures = 0, stale = 0;
for (const [stem, preset] of Object.entries(FILES)) {
  const p = P.build({ preset });
  const css = P.toCSS(p, { header: header(p, stem) });
  const file = path.join(ROOT, 'assets', stem + '.css');
  if (check) {
    let cur = ''; try { cur = readFileSync(file, 'utf8'); } catch {}
    if (cur !== css) { stale++; console.log(`STALE ${stem}.css`); }
  } else writeFileSync(file, css);

  const rows = p.report.filter(r => !r.more);
  const worstText = rows.filter(r => r.kind === 'text').sort((a, b) => a.ratio / a.target - b.ratio / b.target)[0];
  console.log(`\n${stem}.css  ${p.label}  (${p.from})`);
  console.log(`  ${rows.length} checks + ${p.report.length - rows.length} increased-contrast, ${p.failures.length} failing; ` +
    `tightest text: ${worstText.tone} ${worstText.role} ${worstText.ratio.toFixed(2)}:1 vs ${worstText.target} on ${worstText.against}`);
  for (const tone of ['light', 'dark']) {
    const line = rows.filter(r => r.tone === tone)
      .map(r => `${r.pass ? '' : '!!'}${r.role} ${r.ratio.toFixed(2)}`).join(' · ');
    console.log(`  ${tone.padEnd(5)} ${line}`);
  }
  for (const f of p.failures) console.log(`  FAIL ${f.tone} ${f.role} ${f.value} ${f.ratio.toFixed(2)}:1 < ${f.target} on ${f.against}`);
  failures += p.failures.length;
}
if (check) console.log(stale ? `\n${stale} stale file(s) — run node tools/gen-palettes.mjs` : '\nall generated files current');
process.exit(failures || stale ? 1 : 0);
